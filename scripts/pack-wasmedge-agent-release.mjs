#!/usr/bin/env node

// TODO: Remove this R2 tarball packer once wasmedge-agent and its internal workspace
// dependencies are published through a real npm release flow.

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
	cpSync,
	existsSync,
	lstatSync,
	mkdirSync,
	renameSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { basename, dirname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaultOutputDir = join(root, "packages", "coding-agent", "release");
const defaultBaseUrl = process.env.WASMEDGE_AGENT_DOWNLOAD_BASE_URL;
const publicPackageName = process.env.WASMEDGE_AGENT_PACKAGE_NAME || "wasmedge-agent";
const publicCommandName = process.env.WASMEDGE_AGENT_CMD || "wasmedge-agent";
const releaseChannels = new Set(["stable", "beta"]);
/** What the canonical command in the published bin map points at.
 *
 *  One constant, used both to write the bin map and to decide what a built
 *  package must contain, so the two cannot drift: a bin entry naming a file
 *  the tarball does not carry is a package that installs and then fails on
 *  first run, and npm reports nothing at pack time. */
export const PUBLIC_BIN_TARGET = "dist/bundle/cli.js";

/** What the deprecated command alias points at instead.
 *
 *  Its own entry point, not the canonical one, because that is the only thing
 *  the invoked identity survives. npm links a POSIX command by symlinking the
 *  name at its target, so `basename(process.argv[1])` really is the name the
 *  user typed there -- but on Windows npm generates `.cmd` and PowerShell
 *  shims that launch node with the *target* path, so argv[1] is the bundle
 *  entry and an alias sharing that entry cannot tell it was invoked as the
 *  alias. The deprecation notice then silently does not exist on that
 *  platform, which is the one place a one-release warning cannot afford to be
 *  missing.
 *
 *  Written here rather than built, so no build config has to know about a
 *  file that exists for one release. */
export const PUBLIC_LEGACY_BIN_TARGET = "dist/bundle/prime-agent.js";

/** The alias entry point's source.
 *
 *  The marker name is duplicated from config.ts's LEGACY_ALIAS_ENV, because
 *  this file is plain JavaScript run before any build and cannot import it.
 *  The covering test reads the constant from config.ts and asserts it appears
 *  here, so the two cannot drift apart silently.
 *
 *  The import is dynamic because a static one is hoisted above everything
 *  else in the module: the CLI would run before the marker was set. */
const LEGACY_ALIAS_SHIM_SOURCE = `#!/usr/bin/env node
// Entry point for the deprecated command alias, generated by
// scripts/pack-wasmedge-agent-release.mjs. warnIfLegacyAlias() in config.ts
// reads this marker once, deletes it so no child process inherits it, and
// warns.
process.env.WASMEDGE_AGENT_LEGACY_ALIAS = "1";
await import("./cli.js");
`;

/** Writes the alias entry point into a staged package, and returns its path.
 *
 *  Exported so the covering test can drive it against a directory it owns,
 *  the way missingReleaseArtifacts is. */
export function writeLegacyAliasShim(packageRoot) {
	const target = join(packageRoot, PUBLIC_LEGACY_BIN_TARGET);
	mkdirSync(dirname(target), { recursive: true });
	// Executable: npm sets the bit on a bin target at install time, but a
	// tarball whose entry is not executable to begin with has been enough to
	// break direct-from-tarball runs before.
	writeFileSync(target, LEGACY_ALIAS_SHIM_SOURCE, { mode: 0o755 });
	return target;
}

const releasePackages = [
	{ packageDir: "ai", publicName: undefined, artifactName: "wasmedge-agent-ai" },
	{ packageDir: "tui", publicName: undefined, artifactName: "wasmedge-agent-tui" },
	{ packageDir: "agent", publicName: undefined, artifactName: "wasmedge-agent-core" },
	{ packageDir: "coding-agent", publicName: publicPackageName, artifactName: publicPackageName },
];

function parseArgs(args) {
	const parsed = {
		baseUrl: defaultBaseUrl,
		channel: "stable",
		outDir: defaultOutputDir,
		version: undefined,
	};

	for (let i = 0; i < args.length; i += 1) {
		const arg = args[i];
		switch (arg) {
			case "--channel": {
				const value = args[i + 1];
				if (!value || !releaseChannels.has(value)) {
					throw new Error("--channel must be stable or beta");
				}
				parsed.channel = value;
				i += 1;
				break;
			}
			case "--base-url": {
				const value = args[i + 1];
				if (!value) throw new Error("--base-url requires a value");
				parsed.baseUrl = value;
				i += 1;
				break;
			}
			case "--out-dir": {
				const value = args[i + 1];
				if (!value) throw new Error("--out-dir requires a value");
				parsed.outDir = resolve(root, value);
				i += 1;
				break;
			}
			case "--version": {
				const value = args[i + 1];
				if (!value) throw new Error("--version requires a value");
				parsed.version = normalizeVersion(value);
				i += 1;
				break;
			}
			case "--help":
			case "-h":
				printHelp();
				process.exit(0);
				break;
			default:
				throw new Error(`Unknown argument: ${arg}`);
		}
	}

	if (!parsed.baseUrl) {
		throw new Error("--base-url or WASMEDGE_AGENT_DOWNLOAD_BASE_URL is required");
	}

	parsed.baseUrl = parsed.baseUrl.replace(/\/+$/, "");
	return parsed;
}

function printHelp() {
	console.log(`Usage: node scripts/pack-wasmedge-agent-release.mjs --base-url url [--channel stable|beta] [--version x.y.z] [--out-dir path]

Creates private npm tarballs for R2 distribution:

  <out-dir>/artifacts/wasmedge-agent-<version>.tgz
  <out-dir>/artifacts/wasmedge-agent-ai-<version>.tgz
  <out-dir>/artifacts/wasmedge-agent-core-<version>.tgz
  <out-dir>/artifacts/wasmedge-agent-tui-<version>.tgz
  <out-dir>/artifacts/SHA256SUMS
  <out-dir>/artifacts/<channel>
  <out-dir>/artifacts/latest.json (stable) or beta.json (beta)
`);
}

function normalizeVersion(version) {
	const normalized = version.startsWith("v") ? version.slice(1) : version;
	if (!/^[0-9A-Za-z.-]+$/.test(normalized)) {
		throw new Error(`Invalid release version: ${version}`);
	}
	return normalized;
}

function readJson(path) {
	return JSON.parse(readFileSync(path, "utf8"));
}

function writeJson(path, value) {
	writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
}

function packagePath(packageDir) {
	return join(root, "packages", packageDir);
}

function assertSafeOutputDir(outDir) {
	const relativeToReleaseRoot = relative(defaultOutputDir, outDir);
	if (relativeToReleaseRoot === "" || (!relativeToReleaseRoot.startsWith("..") && !isAbsolute(relativeToReleaseRoot))) {
		return;
	}
	throw new Error(`Refusing to remove output directory outside ${defaultOutputDir}: ${outDir}`);
}

function packageJsonPath(packageDir) {
	return join(packagePath(packageDir), "package.json");
}

/** True when `path` is what `kind` says it is, and false for anything else --
 *  absent, the wrong kind, unreadable, or a symbolic link.
 *
 *  lstat, not stat: a link at the command target satisfied the regular-file
 *  requirement by answering for whatever it pointed at, which is a fact about
 *  the build machine and not about the tarball. Nothing this repo tracks or
 *  builds is a link, so reading one as neither a file nor a directory costs
 *  nothing and closes that. */
function isFilesystemKind(path, kind) {
	try {
		const stats = lstatSync(path);
		return kind === "file" ? stats.isFile() : stats.isDirectory();
	} catch {
		return false;
	}
}

/** Build outputs a package must have before it can be packed: its dist tree,
 *  plus every file named here relative to the package root. Pure and exported
 *  so the covering test can drive it against a directory it controls.
 *
 *  Kind-checked, not merely present: a directory at the bin target satisfies
 *  existsSync and produces a published bin entry pointing at something no
 *  shell can run, which npm reports at neither pack nor install time. The same
 *  goes the other way for the dist tree. */
export function missingReleaseArtifacts(packageRoot, requiredFiles = []) {
	const missing = [];
	const dist = join(packageRoot, "dist");
	if (!isFilesystemKind(dist, "directory")) missing.push(dist);
	for (const relativePath of requiredFiles) {
		const target = join(packageRoot, relativePath);
		if (!isFilesystemKind(target, "file")) missing.push(target);
	}
	return missing;
}

function requireBuiltPackage(packageDir) {
	const dist = join(packagePath(packageDir), "dist");
	if (!existsSync(dist)) {
		throw new Error(`Missing ${dist}. Run npm run build before packing a release.`);
	}
}

function copyIfExists(source, target) {
	if (existsSync(source)) {
		cpSync(source, target, { recursive: true });
	}
}

function npmTarballName(packageName, version) {
	return `${packageName.replace(/^@/, "").replace("/", "-")}-${version}.tgz`;
}

function releaseTarballUrl(baseUrl, version, tarballFile) {
	return `${baseUrl}/releases/v${version}/${tarballFile}`;
}

function rewriteInternalDependencies(dependencies, internalPackageUrls) {
	if (!dependencies) return undefined;
	const rewritten = {};
	for (const [name, range] of Object.entries(dependencies)) {
		rewritten[name] = internalPackageUrls.get(name) || range;
	}
	return rewritten;
}

function releaseScripts(sourceScripts) {
	if (!sourceScripts?.postinstall) return undefined;
	return {
		postinstall: sourceScripts.postinstall,
	};
}

export function createReleasePackageJson(sourcePackage, packageName, releaseVersion, internalPackageUrls) {
	const packageJson = {
		...sourcePackage,
		name: packageName,
		version: releaseVersion,
		dependencies: rewriteInternalDependencies(sourcePackage.dependencies, internalPackageUrls),
		optionalDependencies: rewriteInternalDependencies(sourcePackage.optionalDependencies, internalPackageUrls),
		scripts: releaseScripts(sourcePackage.scripts),
	};

	delete packageJson.devDependencies;
	delete packageJson.overrides;
	delete packageJson.private;

	if (packageName === publicPackageName) {
		packageJson.bin = {
			[publicCommandName]: "dist/bundle/cli.js",
			// Compatibility alias, one release only. See the CHANGELOG's Unreleased
			// section: warnIfLegacyAlias() in config.ts warns on stderr when the CLI
			// is invoked through this name, and that warning is unreachable unless
			// something actually installs the name.
			//
			// npm links a global command by name, not by owning package, so this
			// entry takes that command away from upstream's package if upstream is
			// also installed globally -- silently, and uninstalling either package
			// then leaves the other's command dangling. The CHANGELOG states that
			// scope; the alias is aimed at this fork's own pre-rename users, not at
			// machines running both.
			//
			// Its own target, not the canonical one: see PUBLIC_LEGACY_BIN_TARGET.
			"prime-agent": PUBLIC_LEGACY_BIN_TARGET,
		};
		packageJson.piConfig = {
			...(packageJson.piConfig || {}),
			name: publicCommandName,
			configDir: ".wasmedge-agent",
		};
	}

	return packageJson;
}

function copyPackageContents(sourceDir, targetDir, packageJson) {
	mkdirSync(targetDir, { recursive: true });
	writeJson(join(targetDir, "package.json"), packageJson);

	for (const entry of ["dist", "docs", "examples", "skills", "postinstall.cjs", "README.md", "CHANGELOG.md"]) {
		copyIfExists(join(sourceDir, entry), join(targetDir, entry));
	}
}

function run(command, args, cwd) {
	const result = spawnSync(command, args, {
		cwd,
		stdio: "pipe",
		encoding: "utf8",
	});

	if (result.status !== 0) {
		if (result.stdout) process.stdout.write(result.stdout);
		if (result.stderr) process.stderr.write(result.stderr);
		throw new Error(`${command} ${args.join(" ")} failed with exit code ${result.status}`);
	}

	if (result.stderr) process.stderr.write(result.stderr);
	return result.stdout.trim();
}

function sha256File(path) {
	const hash = createHash("sha256");
	hash.update(readFileSync(path));
	return hash.digest("hex");
}

function main() {
	const args = parseArgs(process.argv.slice(2));
	const sourcePackages = new Map(
		releasePackages.map((releasePackage) => [
			releasePackage.packageDir,
			readJson(packageJsonPath(releasePackage.packageDir)),
		]),
	);
	const cliPackage = sourcePackages.get("coding-agent");
	const releaseVersion = args.version || normalizeVersion(process.env.WASMEDGE_AGENT_VERSION || cliPackage.version);

	for (const releasePackage of releasePackages) {
		requireBuiltPackage(releasePackage.packageDir);
	}

	// Dependency keys stay on the source package names so existing compiled imports
	// keep resolving, while release package names and artifact filenames are branded.
	const sourcePackageNames = new Map();
	const packageNames = new Map();
	const artifactFiles = new Map();
	for (const releasePackage of releasePackages) {
		const sourcePackage = sourcePackages.get(releasePackage.packageDir);
		const packageName = releasePackage.publicName || releasePackage.artifactName || sourcePackage.name;
		sourcePackageNames.set(releasePackage.packageDir, sourcePackage.name);
		packageNames.set(releasePackage.packageDir, packageName);
		artifactFiles.set(
			releasePackage.packageDir,
			npmTarballName(releasePackage.artifactName || packageName, releaseVersion),
		);
	}

	const internalPackageUrls = new Map();
	for (const releasePackage of releasePackages) {
		if (releasePackage.packageDir === "coding-agent") continue;
		const sourcePackageName = sourcePackageNames.get(releasePackage.packageDir);
		const artifactFile = artifactFiles.get(releasePackage.packageDir);
		internalPackageUrls.set(sourcePackageName, releaseTarballUrl(args.baseUrl, releaseVersion, artifactFile));
	}

	const stagingRoot = join(args.outDir, "packages");
	const artifactsDir = join(args.outDir, "artifacts");
	assertSafeOutputDir(args.outDir);
	rmSync(args.outDir, { force: true, recursive: true });
	mkdirSync(stagingRoot, { recursive: true });
	mkdirSync(artifactsDir, { recursive: true });

	const tarballs = [];
	for (const releasePackage of releasePackages) {
		const sourcePackage = sourcePackages.get(releasePackage.packageDir);
		const packageName = packageNames.get(releasePackage.packageDir);
		const stagingDir = join(stagingRoot, releasePackage.packageDir);
		const packageJson = createReleasePackageJson(
			sourcePackage,
			packageName,
			releaseVersion,
			internalPackageUrls,
		);

		copyPackageContents(packagePath(releasePackage.packageDir), stagingDir, packageJson);
		if (packageName === publicPackageName) {
			// Only the public package installs commands, so only it carries the
			// alias entry the bin map above points at.
			writeLegacyAliasShim(stagingDir);
		}

		const tarballName = run("npm", ["pack", stagingDir, "--pack-destination", artifactsDir, "--silent"], root)
			.split("\n")
			.at(-1);
		if (!tarballName) {
			throw new Error(`npm pack did not report a tarball name for ${packageName}`);
		}

		const tarballPath = join(artifactsDir, basename(tarballName));
		if (!existsSync(tarballPath) || !statSync(tarballPath).isFile()) {
			throw new Error(`npm pack did not create ${tarballPath}`);
		}

		const artifactFile = artifactFiles.get(releasePackage.packageDir);
		const artifactPath = join(artifactsDir, artifactFile);
		if (tarballPath !== artifactPath) {
			rmSync(artifactPath, { force: true });
			renameSync(tarballPath, artifactPath);
		}

		tarballs.push({
			name: packageName,
			file: artifactFile,
			sha256: sha256File(artifactPath),
		});
	}

	tarballs.sort((left, right) => left.file.localeCompare(right.file));
	writeFileSync(
		join(artifactsDir, "SHA256SUMS"),
		tarballs.map((tarball) => `${tarball.sha256}  ${tarball.file}`).join("\n") + "\n",
	);
	writeFileSync(join(artifactsDir, args.channel), `v${releaseVersion}\n`);
	const manifestName = args.channel === "stable" ? "latest.json" : "beta.json";
	writeJson(join(artifactsDir, manifestName), {
		version: `v${releaseVersion}`,
		package: publicPackageName,
		tarball: `releases/v${releaseVersion}/${artifactFiles.get("coding-agent")}`,
		tarballs: tarballs.map((tarball) => ({
			package: tarball.name,
			file: tarball.file,
			sha256: tarball.sha256,
		})),
	});

	for (const tarball of tarballs) {
		console.log(`Created ${join(artifactsDir, tarball.file)}`);
	}
}

// Only when run as a script. Importing this file is how the covering test
// reads the generated manifest -- including the legacy bin entry, whose whole
// point is that the release ships it -- without a build and without packing.
const invokedDirectly = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
	try {
		main();
	} catch (error) {
		console.error(error instanceof Error ? error.message : String(error));
		process.exit(1);
	}
}
