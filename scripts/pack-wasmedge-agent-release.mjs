/** What the canonical command in the published bin map points at.
 *
 *  One constant, used both to write the bin map and to decide what a built
 *  package must contain, so the two cannot drift: a bin entry naming a file
 *  the tarball does not carry is a package that installs and then fails on
 *  first run, and npm reports nothing at pack time. */
export const PUBLIC_BIN_TARGET = "dist/bundle/cli.js";

/** What the deprecated command alias points at instead.
 *
 *  Its own entry point, not the canonical one, because that is the only thing
 *  the invoked identity survives. npm links a POSIX command by symlinking the
 *  name at its target, so `basename(process.argv[1])` really is the name the
 *  user typed there -- but on Windows npm generates `.cmd` and PowerShell
 *  shims that launch node with the *target* path, so argv[1] is the bundle
 *  entry and an alias sharing that entry cannot tell it was invoked as the
 *  alias. The deprecation notice then silently does not exist on that
 *  platform, which is the one place a one-release warning cannot afford to be
 *  missing.
 *
 *  Written here rather than built, so no build config has to know about a
 *  file that exists for one release. */
export const PUBLIC_LEGACY_BIN_TARGET = "dist/bundle/prime-agent.js";

/** The alias entry point's source.
 *
 *  The marker name is duplicated from config.ts's LEGACY_ALIAS_ENV, because
 *  this file is plain JavaScript run before any build and cannot import it.
 *  The covering test reads the constant from config.ts and asserts it appears
 *  here, so the two cannot drift apart silently.
 *
 *  The import is dynamic because a static one is hoisted above everything
 *  else in the module: the CLI would run before the marker was set. */
const LEGACY_ALIAS_SHIM_SOURCE = `#!/usr/bin/env node
// Entry point for the deprecated command alias, generated by
// scripts/pack-wasmedge-agent-release.mjs. warnIfLegacyAlias() in config.ts
// reads this marker once, deletes it so no child process inherits it, and
// warns.
process.env.WASMEDGE_AGENT_LEGACY_ALIAS = "1";
await import("./cli.js");
`;

/** Writes the alias entry point into a staged package, and returns its path.
 *
 *  Exported so the covering test can drive it against a directory it owns,
 *  the way missingReleaseArtifacts is. */
export function writeLegacyAliasShim(packageRoot) {
	const target = join(packageRoot, PUBLIC_LEGACY_BIN_TARGET);
	mkdirSync(dirname(target), { recursive: true });
	// Executable: npm sets the bit on a bin target at install time, but a
	// tarball whose entry is not executable to begin with has been enough to
	// break direct-from-tarball runs before.
	writeFileSync(target, LEGACY_ALIAS_SHIM_SOURCE, { mode: 0o755 });
	return target;
}

